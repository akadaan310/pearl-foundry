/**
 * Canonical JSON and SHA-256. Both are isomorphic: they run identically on the
 * server and in the browser, so a visitor's browser can recompute any hash
 * the server reports.
 *
 * canonical() matches Python's
 *   json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
 * which is what substrateIO hashes (substrate/artifacts.py).
 */

export type Json = null | boolean | number | string | Json[] | { [k: string]: Json };

function str(s: string): string {
  // JSON.stringify escapes quotes, backslashes and control characters the same way Python does;
  // ensure_ascii additionally escapes everything above 0x7F.
  return JSON.stringify(s).replace(/[\u0080-\uffff]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}

export function canonical(v: Json): string {
  if (v === null) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error("canonical: non-finite number");
    if (!Number.isInteger(v)) throw new Error("canonical: only integers are canonical here");
    return String(v);
  }
  if (typeof v === "string") return str(v);
  if (Array.isArray(v)) return "[" + v.map(canonical).join(",") + "]";
  const keys = Object.keys(v).sort();
  return "{" + keys.map((k) => str(k) + ":" + canonical(v[k] as Json)).join(",") + "}";
}

